// ---- tracking (ported from finger-frame-effect main.js) ----
function toPixel(lm) {
  return { x: lm.x * canvas.width, y: lm.y * canvas.height };
}
function dist(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
function lerpPt(a, b, t) {
  return { x: a.x + (b.x - a.x) * t, y: a.y + (b.y - a.y) * t };
}
function polygonArea(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const p = pts[i], q = pts[(i + 1) % pts.length];
    a += p.x * q.y - q.x * p.y;
  }
  return Math.abs(a / 2);
}

function computeQuad(hands) {
  if (hands.length !== 2) return null;
  const info = hands.map((lm) => ({
    index: toPixel(lm[INDEX_TIP]),
    thumb: toPixel(lm[THUMB_TIP]),
    wristX: toPixel(lm[WRIST]).x,
    scale: dist(toPixel(lm[WRIST]), toPixel(lm[MIDDLE_MCP])) + 1,
  }));
  const needed = frameActive ? 0.2 : 0.75;
  for (const hd of info) {
    if (dist(hd.thumb, hd.index) < hd.scale * needed) return null;
  }
  info.sort((a, b) => a.wristX - b.wristX);
  const [A, B] = info;
  const pts = [A.index, B.index, B.thumb, A.thumb];
  const cx = pts.reduce((s, p) => s + p.x, 0) / 4;
  const cy = pts.reduce((s, p) => s + p.y, 0) / 4;
  const hull = [...pts].sort(
    (a, b) => Math.atan2(a.y - cy, a.x - cx) - Math.atan2(b.y - cy, b.x - cx)
  );
  const minArea = frameActive ? 0.0005 : 0.005;
  if (polygonArea(hull) < canvas.width * canvas.height * minArea) return null;
  return pts;
}

function updateTracker(hands) {
  const target = computeQuad(hands);
  if (target) {
    if (!corners) {
      lostFrames = 0;
      frameActive = true;
      jumpFrames = 0;
      corners = target;
      presence = Math.min(1, presence + 0.12);
    } else {
      const moved = target.reduce((s, p, i) => s + dist(p, corners[i]), 0) / 4;
      if (moved > canvas.width * 0.3 && ++jumpFrames < JUMP_CONFIRM_FRAMES) {
        if (++lostFrames > MAX_LOST_FRAMES) presence = Math.max(0, presence - 0.05);
      } else {
        lostFrames = 0;
        frameActive = true;
        jumpFrames = 0;
        const alpha = Math.min(0.85, Math.max(0.35, moved / (canvas.width * 0.05)));
        corners = corners.map((c, i) => lerpPt(c, target[i], alpha));
        presence = Math.min(1, presence + 0.12);
      }
    }
  } else if (corners && ++lostFrames <= MAX_LOST_FRAMES) {
    presence = Math.min(1, presence + 0.12);
  } else {
    presence = Math.max(0, presence - 0.05);
    if (presence === 0) {
      corners = null;
      frameActive = false;
      jumpFrames = 0;
    }
  }
}

function resetTracking() {
  corners = null;
  presence = 0;
  frameActive = false;
  lostFrames = 0;
  jumpFrames = 0;
  trackerState = null;
  stabilizedTracker = TRACKING_MODE === "stabilized"
    ? new StabilizedFrameTracker(canvas.width, canvas.height)
    : null;
  perspectiveCompositor = COMPOSITING_MODE === "legacy"
    ? null
    : new PerspectiveCanvasCompositor(
      canvas.width,
      canvas.height,
      COMPOSITING_MODE === "perspective_occlusion",
      parallaxEnabled,
    );
  portalCrossingController = portalCrossingEnabled && COMPOSITING_MODE !== "legacy"
    ? new PortalCrossingController(
        canvas.width,
        canvas.height,
        PORTAL_CROSSING_CONFIG,
        {
          stylePreset: styleSelect.value,
          customPromptPresent: !!styleCustom.value.trim(),
          referenceImagePresent: !!referenceImageSelection.file,
        },
      )
    : null;
  portalTransition = Object.freeze({
    state: TransitionState.INACTIVE,
    coverage: 0,
    progress: 0,
    confidence: 0,
    expandedQuad: null,
    portalId: null,
  });
  currentHands = [];
}

function updateSelectedTracker(hands) {
  if (TRACKING_MODE === "legacy") {
    updateTracker(hands);
    trackerState = {
      rawQuad: computeQuad(hands),
      stabilizedQuad: corners,
      confidence: presence,
      detectionState: corners ? "legacy" : "lost",
      isPredicted: false,
      dropoutFrames: lostFrames,
    };
    return trackerState;
  }
  if (!stabilizedTracker) {
    stabilizedTracker = new StabilizedFrameTracker(canvas.width, canvas.height);
  }
  const rawQuad = computeQuad(hands);
  trackerState = stabilizedTracker.update(rawQuad);
  corners = trackerState.stabilizedQuad;
  presence = trackerState.confidence;
  frameActive = stabilizedTracker.active;
  lostFrames = trackerState.dropoutFrames;
  return trackerState;
}

function updatePortalTransition() {
  if (!portalCrossingController) {
    portalTransition = Object.freeze({
      state: corners ? TransitionState.PORTAL_VISIBLE : TransitionState.INACTIVE,
      coverage: 0,
      progress: 0,
      confidence: presence,
      expandedQuad: corners,
      portalId: null,
    });
    return portalTransition;
  }
  portalCrossingController.setGenerationMetadata({
    stylePreset: styleSelect.value,
    customPromptPresent: !!styleCustom.value.trim(),
    referenceImagePresent: !!referenceImageSelection.file,
  });
  portalTransition = portalCrossingController.update({
    quad: corners,
    confidence: trackerState?.confidence || 0,
    detectionState: trackerState?.detectionState || "invalid",
    forceProgress: FORCED_TRANSITION_PROGRESS,
  });
  return portalTransition;
}

// ---- rendering ----
function quadPath(q) {
  ctx.beginPath();
  ctx.moveTo(q[0].x, q[0].y);
  for (let i = 1; i < 4; i++) ctx.lineTo(q[i].x, q[i].y);
  ctx.closePath();
}

function drawWindow(q) {
  ctx.save();
  quadPath(q);
  ctx.clip();
  ctx.globalAlpha = presence;
  if (haveAI) {
    ctx.drawImage(sty, 0, 0, canvas.width, canvas.height);
  } else {
    ctx.filter = "hue-rotate(140deg) saturate(1.7) contrast(1.15)";
    ctx.drawImage(orig, 0, 0, canvas.width, canvas.height);
    ctx.filter = "none";
  }
  ctx.restore();
  ctx.globalAlpha = 1;
}

function drawOutline(q, t) {
  ctx.save();
  ctx.globalAlpha = presence;
  quadPath(q);
  ctx.setLineDash([10, 8]);
  ctx.lineDashOffset = -t * 40;
  ctx.lineWidth = 2;
  ctx.strokeStyle = "rgba(255,255,255,0.95)";
  ctx.shadowColor = "rgba(0,0,0,0.5)";
  ctx.shadowBlur = 6;
  ctx.stroke();
  ctx.setLineDash([]);
  ctx.lineDashOffset = 0;
  ctx.shadowBlur = 0;
  q.forEach((p, i) => {
    const r = 7 + Math.sin(t * 3 + i * 1.5) * 1.5;
    const halo = (t * 0.8 + i * 0.25) % 1;
    ctx.beginPath();
    ctx.arc(p.x, p.y, r + halo * 14, 0, Math.PI * 2);
    ctx.strokeStyle = `rgba(255,255,255,${0.5 * (1 - halo) * presence})`;
    ctx.lineWidth = 2;
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(p.x, p.y, r, 0, Math.PI * 2);
    ctx.fillStyle = "#fff";
    ctx.fill();
    ctx.beginPath();
    ctx.arc(p.x, p.y, r, 0, Math.PI * 2);
    ctx.strokeStyle = "rgba(0,0,0,0.25)";
    ctx.lineWidth = 1.5;
    ctx.stroke();
  });
  ctx.restore();
}

function renderPortal(t) {
  const renderQuad = portalCrossingEnabled
    ? portalTransition.expandedQuad
    : corners;
  const isFullAI = portalTransition.state === TransitionState.FULL_AI;
  if (!renderQuad || (!isFullAI && presence <= 0.01)) return;
  if (COMPOSITING_MODE === "legacy") {
    drawWindow(renderQuad);
    drawOutline(renderQuad, t);
  } else {
    perspectiveCompositor.draw({
      context: ctx,
      portalSource: haveAI ? sty : orig,
      originalSource: orig,
      quad: renderQuad,
      motionQuad: corners,
      hands: currentHands,
      trackerState,
      filter: haveAI ? "none" : "hue-rotate(140deg) saturate(1.7) contrast(1.15)",
      transitionProgress: portalTransition.progress,
    });
  }
}

let lastVideoTime = -1;
function loop() {
  if (!orig.paused && !orig.ended) requestAnimationFrame(loop);

  ctx.drawImage(orig, 0, 0, canvas.width, canvas.height);

  if (landmarker && orig.currentTime !== lastVideoTime) {
    lastVideoTime = orig.currentTime;
    const res = landmarker.detectForVideo(orig, performance.now());
    currentHands = res.landmarks || [];
    updateSelectedTracker(currentHands);
    updatePortalTransition();
  }

  // Keep the stylized video in step with the original.
  if (haveAI && Math.abs(sty.currentTime - orig.currentTime) > 0.15) {
    sty.currentTime = orig.currentTime;
  }

  renderPortal(orig.currentTime);
}

async function playThrough() {
  resetTracking();
  orig.currentTime = 0;
  if (haveAI) {
    sty.currentTime = 0;
    sty.play();
  }
  await orig.play();
  requestAnimationFrame(loop);
}

