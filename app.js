async function loadVideo(file) {
  stopMedia();
  generationAbortController?.abort();
  clearWorkflowStage();
  try {
    validateVideoFile(file);
    setWorkflowStage("Analyzing video");
    status("Analyzing video…");
    revokeUrl("source");
    revokeUrl("stylized");
    sourceObjectUrl = URL.createObjectURL(file);
    orig.src = sourceObjectUrl;
    originalPreview.src = sourceObjectUrl;
    await waitForMetadata(orig, "The browser could not decode this video.");
    validateVideoMetadata({
      duration: orig.duration,
      width: orig.videoWidth,
      height: orig.videoHeight,
    });
    videoFile = file;
    haveAI = false;
    usePlaceholder = false;
    canvas.width = orig.videoWidth;
    canvas.height = orig.videoHeight;
    resetTracking();
    stage.style.display = "flex";
    drop.classList.add("compact");
    drawPoster();
    updateWorkflow("video_loaded");
    clearWorkflowStage();
    status(
      `Loaded ${file.name} (${orig.videoWidth}×${orig.videoHeight}, ` +
      `${orig.duration.toFixed(1)}s). Choose a look, then generate.`
    );
    if (!landmarker) initLandmarker().catch((error) => {
      console.error("Tracking initialization failed", error);
      status("Tracking could not start. Check your connection and reload the page.");
    });
  } catch (error) {
    console.error("Video load failed", error);
    revokeUrl("source");
    videoFile = null;
    fileInput.value = "";
    updateWorkflow("reset");
    clearWorkflowStage();
    status(`Video unavailable: ${error.message || error}`);
  }
}

function waitForMetadata(video, message) {
  return new Promise((resolve, reject) => {
    const cleanup = () => {
      video.removeEventListener("loadedmetadata", loaded);
      video.removeEventListener("error", failed);
    };
    const loaded = () => { cleanup(); resolve(); };
    const failed = () => { cleanup(); reject(new Error(message)); };
    video.addEventListener("loadedmetadata", loaded, { once: true });
    video.addEventListener("error", failed, { once: true });
  });
}

