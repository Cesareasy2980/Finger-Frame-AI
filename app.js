function setWorkflowStage(stageName, detail = "") {
  const index = WORKFLOW_STAGES.indexOf(stageName);
  activeWorkflowStage = index < 0 ? null : stageName;
  progressPanel.classList.toggle("hidden", index < 0);
  if (index < 0) return;
  progressFill.style.width = `${((index + 1) / WORKFLOW_STAGES.length) * 100}%`;
  progressLabel.textContent = detail ? `${stageName} — ${detail}` : stageName;
}

function clearWorkflowStage() {
  activeWorkflowStage = null;
  progressPanel.classList.add("hidden");
  progressFill.style.width = "0";
  progressLabel.textContent = "";
}

function friendlyGenerationError(error, hasReference) {
  const detail = String(error?.message || error);
  if (/404|403|region|location|not available|not found/i.test(detail)) {
    return "This Gemini video model is not available for the current key or region.";
  }
  if (hasReference) return `Reference-image generation failed: ${detail}`;
  if (activeWorkflowStage === "Uploading media") return `Gemini upload failed: ${detail}`;
  return `Gemini generation failed: ${detail}`;
}

