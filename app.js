const sleep = (ms, signal) => new Promise((resolve, reject) => {
  const timer = setTimeout(resolve, ms);
  signal?.addEventListener("abort", () => {
    clearTimeout(timer);
    reject(new DOMException("Cancelled", "AbortError"));
  }, { once: true });
});

function fileToBase64(file) {
  return new Promise((resolve, reject) => {
    const fr = new FileReader();
    fr.onload = () => resolve(fr.result.split(",")[1]);
    fr.onerror = reject;
    fr.readAsDataURL(file);
  });
}

async function gemFetch(key, path, init = {}) {
  const res = await fetch(`${GEMINI_BASE}/${path}`, {
    ...init,
    headers: {
      "x-goog-api-key": key,
      ...(init.body ? { "Content-Type": "application/json" } : {}),
      ...(init.headers || {}),
    },
  });
  if (!res.ok) {
    let detail = res.statusText;
    try {
      detail = (await res.json())?.error?.message || detail;
    } catch {}
    throw new Error(`${res.status}: ${detail.slice(0, 160)}`);
  }
  return res.json();
}

// The Interactions API is in preview; be liberal about where the output
// video and status live in the response. Verified live shape: the video is
// in steps[].content[] on the step with type "model_output".
function findOutputVideo(inter) {
  if (inter.output_video) return inter.output_video;
  if (inter.outputVideo) return inter.outputVideo;
  const lists = [inter.outputs, inter.output, inter.content].filter(Array.isArray);
  for (const step of inter.steps || []) {
    if (Array.isArray(step.content)) lists.push(step.content);
  }
  for (const list of lists) {
    const v = list.find(
      (o) => o?.type?.includes?.("video") || o?.video || o?.mime_type?.startsWith?.("video")
    );
    if (v) return v.video || v;
  }
  return null;
}

function isPending(inter) {
  const s = (inter.status || inter.state || "").toLowerCase();
  return ["pending", "in_progress", "processing", "running", "queued"].some((k) =>
    s.includes(k)
  );
}

btnGenerate.addEventListener("click", async () => {
  let generationPrompt;
  try {
    generationPrompt = currentGenerationPrompt();
  } catch (err) {
    promptValidation.textContent = err.message || String(err);
    styleCustom.setAttribute("aria-invalid", "true");
    status("⚠️ " + (err.message || err));
    styleCustom.focus();
    return;
  }
  const key = saveKey();
  if (!key) {
    status("Add your Gemini key above first (or use the placeholder).");
    keyInput.focus();
    return;
  }
  if (!videoFile) return;
  if (videoFile.size > 15 * 1024 * 1024) {
    status("⚠️ Keep the video under ~15MB (a few seconds of 720p) for inline upload.");
    return;
  }
  generationAbortController = new AbortController();
  const { signal } = generationAbortController;
  updateWorkflow("generation_started");
  try {
    setWorkflowStage("Preparing generation");
    status("Preparing generation…");
    const b64 = await fileToBase64(videoFile);

    let referenceImage = null;
    if (referenceImageSelection.file) {
      status("Preparing reference image…");
      try {
        referenceImage = {
          data: await fileToBase64(referenceImageSelection.file),
          mimeType: referenceImageSelection.metadata.mimeType,
        };
      } catch (error) {
        throw new Error(`Reference image preparation failed: ${error.message || error}`);
      }
    }

    setWorkflowStage("Uploading media");
    status("Uploading media to Gemini…");
    let inter = await gemFetch(key, "interactions", {
      method: "POST",
      signal,
      body: JSON.stringify(
        buildGeminiInteractionBody({
          videoData: b64,
          videoMimeType: videoFile.type || "video/mp4",
          prompt: generationPrompt,
          referenceImage,
        }),
      ),
    });
    console.log("interaction response:", inter);

    // Poll the interaction until it settles, if it reports as in-progress.
    const id = inter.id || inter.name;
    let waited = 0;
    setWorkflowStage("Generating AI world");
    while (isPending(inter) && waited < 600) {
      await sleep(5000, signal);
      waited += 5;
      inter = await gemFetch(key, `interactions/${id}`, { signal });
      status(`Generating… (${waited}s, status: ${inter.status || inter.state || "working"})`);
    }

    const vid = findOutputVideo(inter);
    if (!vid) {
      console.error("full response:", inter);
      throw new Error("no video in response — see console for the raw payload");
    }

    status("Processing result…");
    let blob;
    if (vid.data) {
      const bytes = Uint8Array.from(atob(vid.data), (c) => c.charCodeAt(0));
      blob = new Blob([bytes], { type: vid.mime_type || "video/mp4" });
    } else {
      // uri delivery: wait for the file to become ACTIVE, then download.
      let uri = vid.uri || vid.file_uri || vid.url;
      if (!uri) throw new Error("no video data or uri in response");
      const fileName = uri.includes("/files/")
        ? "files/" + uri.split("/files/")[1].split(/[?#]/)[0]
        : uri;
      if (!/^https?:/.test(uri)) uri = `${GEMINI_BASE}/${fileName}:download?alt=media`;
      for (let i = 0; i < 60; i++) {
        const f = await gemFetch(key, fileName, { signal });
        if ((f.state || "").includes("ACTIVE")) break;
        status(`Waiting for the output file… (${(f.state || "processing").toLowerCase()})`);
        await sleep(5000, signal);
      }
      status("Downloading result…");
      const res = await fetch(uri, { headers: { "x-goog-api-key": key }, signal });
      if (!res.ok) throw new Error(`download failed: ${res.status}`);
      blob = await res.blob();
    }

    setWorkflowStage("Finalizing video");
    revokeUrl("stylized");
    stylizedObjectUrl = URL.createObjectURL(blob);
    sty.src = stylizedObjectUrl;
    await waitForMetadata(sty, "Gemini returned a video the browser could not decode.");
    haveAI = true;
    usePlaceholder = false;
    updateWorkflow("generation_finished");
    clearWorkflowStage();
    status("AI video ready — perspective compositing runs during preview or export.");
  } catch (err) {
    console.error(err);
    if (err?.name === "AbortError") {
      updateWorkflow("cancelled");
      clearWorkflowStage();
      status("Generation cancelled. Your uploaded video is still ready.");
      return;
    }
    updateWorkflow("failed");
    status("⚠️ " + friendlyGenerationError(err, !!referenceImageSelection.file));
    clearWorkflowStage();
  } finally {
    generationAbortController = null;
    updateWorkflow("refresh");
  }
});

