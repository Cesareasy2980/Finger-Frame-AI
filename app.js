btnExport.addEventListener("click", async () => {
  if (exporting) return;
  exporting = true;
  generationAbortController = new AbortController();
  const { signal } = generationAbortController;
  updateWorkflow("export_started");
  setWorkflowStage("Tracking hand frame", "export pass");
  status("Rendering the final video…");

  const stream = canvas.captureStream(30);
  const sourceStream = orig.captureStream?.() || orig.mozCaptureStream?.();
  for (const track of sourceStream?.getAudioTracks?.() || []) stream.addTrack(track);
  // Prefer MP4 where the browser can record it (Safari, newer Chrome);
  // fall back to WebM elsewhere.
  const mime = [
    "video/mp4;codecs=avc1.42E01E",
    "video/mp4",
    "video/webm;codecs=vp9",
    "video/webm",
  ].find((m) => MediaRecorder.isTypeSupported(m)) || "video/webm";
  const isMp4 = mime.startsWith("video/mp4");
  try {
    recorder = new MediaRecorder(stream, {
      mimeType: mime,
      videoBitsPerSecond: 10_000_000,
    });
    const chunks = [];
    recorder.ondataavailable = (e) => e.data.size && chunks.push(e.data);
    const finished = new Promise((resolve, reject) => {
      recorder.onerror = () => reject(new Error("The browser recorder could not encode the output."));
      recorder.onstop = resolve;
    });
    orig.onended = () => {
      orig.onended = null;
      setWorkflowStage("Restoring audio");
      if (recorder?.state === "recording") recorder.stop();
    };
    recorder.start(1000);
    await playThrough();
    await finished;
    if (signal.aborted) return;
    setWorkflowStage("Finalizing video");
    const ext = isMp4 ? "mp4" : "webm";
    const blob = new Blob(chunks, { type: isMp4 ? "video/mp4" : "video/webm" });
    revokeUrl("export");
    exportObjectUrl = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = exportObjectUrl;
    a.download = `finger-frame-ai-output.${ext}`;
    a.click();
    status(
      `Exported finger-frame-ai-output.${ext}.` +
      (isMp4 ? "" : " This browser supports WebM recording; use the offline MP4 path for a guaranteed MP4.")
    );
    updateWorkflow("export_finished");
  } catch (error) {
    console.error("Output rendering failed", error);
    if (!signal.aborted) {
      updateWorkflow("failed");
      status(`Output rendering failed: ${error.message || error}`);
    }
  } finally {
    for (const track of stream.getTracks()) track.stop();
    for (const track of sourceStream?.getTracks?.() || []) track.stop();
    recorder = null;
    exporting = false;
    generationAbortController = null;
    clearWorkflowStage();
    updateWorkflow(signal.aborted ? "cancelled" : "refresh");
  }
});

